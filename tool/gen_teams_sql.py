#!/usr/bin/env python3
"""Writes supabase/migrations/20261123000000_nx_fs_v10_teams.sql from tool/teams_v10.py.

Price rule (same formula as lib/core/economy/gem_shop.dart defaultTeamPrice): free teams 0, otherwise
150 at power+accuracy 9 up to 500 at 20, rounded to 10. Every team in the client catalogue gets a catalog row so the
server can price and sell it; retired v9 starter ids are kept but deactivated (their art no longer ships).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from teams_v10 import TEAMS  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, 'supabase', 'migrations', '20261123000000_nx_fs_v10_teams.sql')
FREE = {'nx_core', 'nx_cyan', 'nx_frost_blue'}
# v9 starter ids, the old luxury ids, the old national ids and the old sport ids. Their rows are kept for the players
# who own them (the client maps a retired id to the default team) but they can no longer be bought.
RETIRED = (
    [f'club{i}' for i in range(32, 40)] + [f'nat{i}' for i in range(24, 28)]
    + [f'lux{i}' for i in range(0, 14)] + ['barca_gold']
    + [f'car{i}' for i in range(0, 14)]
    + [f'spt{i}' for i in range(0, 14)]
    + [f'nat{i}' for i in list(range(0, 20)) + [28, 29, 30]]
    + ['elite_realmadrid2']
)


def price(power: int, accuracy: int) -> int:
    score = max(9, min(20, power + accuracy))
    return round((150 + (score - 9) * 350 / 11) / 10) * 10


def esc(s: str) -> str:
    return s.replace("'", "''")


def main() -> None:
    rows = []
    for tid, cat, en, fa, slug, p, a in TEAMS:
        kind = {'clubs': 'club', 'nations': 'nation', 'nx': 'nx', 'cars': 'car', 'sport': 'sport',
                'elite': 'elite', 'legends': 'legend'}[cat]
        cost = 0 if tid in FREE else price(p, a)
        rows.append(f"  ('fs_team:{tid}', {cost}, 'gems', 'team', '{esc(en)}', '{kind}')")
    seed = ',\n'.join(rows)
    retired_list = ',\n  '.join(
        ", ".join(f"'{x}'" for x in RETIRED[i:i + 8]) for i in range(0, len(RETIRED), 8))
    sql = f"""-- Finger soccer v10 catalogue (owner art 2026-11-22): 122 teams in seven categories.
-- Generated by tool/gen_teams_sql.py from tool/teams_v10.py — edit the spec, not this file.
--
-- * Every team the client can field gets an `fs_team:<id>` catalog row, so nx_buy_with_gems can price and sell it.
-- * Prices follow the client's defaultTeamPrice exactly (free 0, otherwise 150 at power+accuracy 9 up to 500 at 20,
--   rounded to 10). The three starter NX coins are free.
-- * `team_kind` (club / nation / nx / car / sport / elite / legend) is the category for the admin shop screen; the
--   existing `kind` column keeps its original meaning ('team'), so nothing that reads it changes.
-- * Every v9 team id whose art is not in the shipped catalogue (the house badges, the old luxury ids, the old
--   national ids, the car / sport ids that were never drawn and the two never-shipped placeholders) keeps its row but
--   is deactivated: an inventory that still holds one resolves to the default team in the client, and nobody can buy
--   them again.
-- Idempotent: inserts only what is missing, then pins the generated price so a re-run heals an edited row, but never
-- touches rows an admin may have repriced for another reason (price is only set where the row was just inserted).

alter table public.nx_catalog add column if not exists team_kind text;

insert into public.nx_catalog(item_id, price, currency, kind, name, team_kind) values
{seed}
on conflict (item_id) do nothing;

-- category tags for rows that existed before this migration (the v9 car / sport sets and the retired starters)
update public.nx_catalog set team_kind = 'car' where team_kind is null and item_id in (
  select 'fs_team:' || unnest(array['club0','club1','club2','club3','club4','club5','club6','club7','club8','club9',
    'club10','club11','club12','club13','club14','club15','club16','club17','club18','club19','club20','club21',
    'club22','club23']));
update public.nx_catalog set team_kind = 'sport' where team_kind is null and item_id in (
  select 'fs_team:' || unnest(array['club24','club25','club26','club27','club28','club29','club30','club31',
    'nat20','nat21','nat22','nat23']));

-- every v9 id that is not in the shipped catalogue: not for sale any more (the client refuses to field them)
update public.nx_catalog set active = false, price = 0, team_kind = 'retired'
 where item_id in ({retired_list});

-- the three starters stay free and always on sale
update public.nx_catalog set price = 0, active = true where item_id in ('fs_team:nx_core', 'fs_team:nx_cyan',
                                                                       'fs_team:nx_frost_blue');
"""
    open(OUT, 'w', encoding='utf-8').write(sql)
    print('wrote', OUT, len(TEAMS), 'teams')


if __name__ == '__main__':
    main()
